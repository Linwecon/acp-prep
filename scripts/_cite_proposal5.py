CITE_RE = re.compile(r"教材|原文\d|根据本章|依据本章|遵循教材|符合教材|依据教材|根据教材|按照教材|参照教材|第\s*\d+\s*章\s*\d+\.\d|本章\d|本章原则|本章四条|本章哪一|本章强调|本章核心|本章明确|本章7|本章4|本章8|本章9|本章10|本章11|本章12|本章5|第\s*\d+\.\d+\s*节")

pairs, rejected = [], []
for ch in sorted(by_ch, key=int):
    for q in by_ch[ch]:
        if q.get("deleted"):
            continue
        qid = f"{ch}-{str(q['seq']).zfill(4)}"
        stem = q.get("stem", "")
        if qid in OVERRIDE:
            pairs.append((qid, stem, OVERRIDE[qid], "manual"))
            continue
        if CITE_RE.search(stem):
            new = rewrite(stem)
            if new == stem:
                continue
            if BREAK_RE.search(new) or re.search(r"教材|原文|本章", new):
                rejected.append((qid, stem, new))
            else:
                pairs.append((qid, stem, new, "auto"))

with open(ROOT / "data" / "curate" / "rebuild" / "cite_final.txt", "w", encoding="utf-8") as f:
    for qid, old, new, kind in pairs:
        f.write(f"=== {qid} [{kind}]\nOLD: {old}\nNEW: {new}\n\n")
with open(ROOT / "data" / "curate" / "rebuild" / "cite_rejected.txt", "w", encoding="utf-8") as f:
    for qid, old, new in rejected:
        f.write(f"=== {qid}\nOLD: {old}\nBAD: {new}\n\n")
