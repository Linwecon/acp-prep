def insert_intro_and_summary():
    text = P.read_text(encoding="utf-8")
    lines = text.splitlines()

    # 插入全局“如何使用本手册 + 贯穿案例”
    if "如何使用本手册" not in text:
        global_block = [
            "",
            "## 如何使用本手册",
            "",
            "> 本手册不是产品说明书，而是围绕“企业新人答疑机器人”这一贯穿案例组织的学习路径。",
            "> 每个大章节先说明“要解决什么问题”，再讲原理、流程、选择、风险和考试关注点。",
            "",
            "**贯穿案例：企业新人答疑机器人**",
            "",
            "我们要逐步构建一个企业新人答疑机器人：它需要听懂员工关于请假、报销、系统报错等问题，",
            "能查制度库和业务系统，能给出有依据的回答，并能以语音方式交互。",
            "第 1 章先理解底层模型，第 2 章设计提示词，第 3 章接入知识库，第 4 章加入工具调用，",
            "第 5 章按需微调，第 6 章部署上线，第 7 章评测效果，第 8 章做安全合规，",
            "第 9 章掌握 API 调用，第 10 章选择阿里云平台，第 11 章扩展多模态，第 12 章选择框架工具。",
            "",
            "---",
        ]
        # 插到第一个 "---" 之前（文档顶部介绍之后）
        idx = None
        for i, l in enumerate(lines):
            if l.strip() == "---":
                idx = i
                break
        if idx is not None:
            lines = lines[:idx] + global_block + lines[idx+1:]

    # 章节导读与总结
    out_lines = []
    i = 0
    while i < len(lines):
        line = lines[i]
        out_lines.append(line)
        m = re.match(r"^## (\d+)\.\s+(.*)$", line)
        if m:
            n = int(m.group(1))
            title = m.group(2).strip()
            cfg = CHAPTERS.get(n)
            if cfg and f"**本章要解决的问题**" not in "\n".join(lines[i:i+6]):
                block = []
                block.append("")
                block.append("> **本章要解决的问题**：" + cfg["problem"])
                block.append(">")
                block.append("> **学习目标**：")
                for obj in cfg["objectives"]:
                    block.append("> - " + obj)
                block.append(">")
                block.append("**本章知识地图**：")
                for item in cfg["map"]:
                    block.append("- " + item)
                block.append("")
                block.append("> **贯穿案例**：" + cfg["case"])
                block.append("")
                # 插到当前 h2 行的下一行
                out_lines.extend(block)
            i += 1
            continue
        i += 1
    lines = out_lines

    # 逐章插入章末总结（在该章结束前的最后一个 '---' 之前）
    # 采用文本级处理更稳妥
    text2 = "\n".join(lines) + "\n"
    h2s = [(m.start(), m.group(1), m.group(2)) for m in re.finditer(r"^## (\d+)\.\s+(.*)$", text2, flags=re.M)]
    for idx, (start, num_s, title) in enumerate(h2s):
        n = int(num_s)
        cfg = CHAPTERS.get(n)
        if not cfg:
            continue
        end = h2s[idx+1][0] if idx+1 < len(h2s) else len(text2)
        chapter_text = text2[start:end]
        marker = "**本章总结与自测**"
        if marker in chapter_text:
            continue
        # 找到本章最后一个 '---'（通常位于下一章标题之前）
        last_hr = chapter_text.rfind("\n---\n")
        insert_pos = last_hr if last_hr != -1 else end
        summary_block = []
        summary_block.append("")
        summary_block.append("### " + title + "：本章总结与自测")
        summary_block.append("")
        summary_block.append("**高密度总结**：")
        for s in cfg["summary"]:
            summary_block.append("- " + s)
        summary_block.append("")
        summary_block.append("**自测题**：")
        for q in cfg["self_test"]:
            summary_block.append("- " + q)
        summary_block.append("")
        summary_text = "\n".join(summary_block)
        if last_hr != -1:
            text2 = text2[:insert_pos] + summary_text + "\n" + text2[insert_pos:]
        else:
            text2 = text2[:end] + summary_text + "\n" + text2[end:]

    P.write_text(text2.rstrip() + "\n", encoding="utf-8")
    print("done")

if __name__ == "__main__":
    insert_intro_and_summary()
